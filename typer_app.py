_instance_guard = None   # kept referenced for the whole process so the lock stays held


def _raise_existing_window():
    """Best effort: bring an already-running Typer window to the front (Windows)."""
    if sys.platform != "win32":
        return
    try:
        import ctypes
        from ctypes import wintypes
        u = ctypes.windll.user32
        u.FindWindowW.argtypes = (wintypes.LPCWSTR, wintypes.LPCWSTR)
        u.FindWindowW.restype = wintypes.HWND
        u.ShowWindow.argtypes = (wintypes.HWND, ctypes.c_int)
        u.SetForegroundWindow.argtypes = (wintypes.HWND,)
        hwnd = u.FindWindowW(None, APP_TITLE)
        if hwnd:
            u.ShowWindow(hwnd, 9)          # SW_RESTORE (un-minimise if needed)
            u.SetForegroundWindow(hwnd)
    except Exception:
        pass


def acquire_single_instance() -> bool:
    """True if this is the only running copy of Typer; False if another is already up
    (then we surface the one already running and this launch should just exit).

    Windows uses a named mutex; macOS/Linux use an advisory lock on a file. Both are
    released automatically when the process ends, so a crash never leaves it stuck."""
    global _instance_guard
    if sys.platform == "win32":
        try:
            import ctypes
            from ctypes import wintypes
            k = ctypes.WinDLL("kernel32", use_last_error=True)
            k.CreateMutexW.argtypes = (wintypes.LPVOID, wintypes.BOOL, wintypes.LPCWSTR)
            k.CreateMutexW.restype = wintypes.HANDLE
            handle = k.CreateMutexW(None, True, "Typer_local_single_instance_v1")
            if ctypes.get_last_error() == 183:       # ERROR_ALREADY_EXISTS
                _raise_existing_window()
                return False
            _instance_guard = handle                  # hold the mutex for the process lifetime
            return True
        except Exception:
            return True                               # never block the app over a failed check
    try:
        import fcntl
        f = open(os.path.join(DATA_DIR, "typer.lock"), "w")
        try:
            fcntl.flock(f.fileno(), fcntl.LOCK_EX | fcntl.LOCK_NB)
        except OSError:
            f.close()
            return False
        _instance_guard = f                           # keep the fd open so the lock is held
        return True
    except Exception:
        return True


def main():
    # Only one Typer at a time: a second launch surfaces the first and exits.
    if not acquire_single_instance():
        return
    root = tk.Tk()
    TyperApp(root)
    root.mainloop()


if __name__ == "__main__":
    main()
