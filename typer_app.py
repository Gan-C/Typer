    def _range_has_tag(self, tag, a, b):
        idx = a
        while self.text.compare(idx, "<", b):
            if tag not in self.text.tag_names(idx):
                return False
            idx = self.text.index(f"{idx}+1c")
        return True

    def _refresh_bolditalic(self, a, b):
        """Keep a combined font on runs that are both bold and italic, so both show."""
        idx = a
        while self.text.compare(idx, "<", b):
            names = self.text.tag_names(idx)
            both = ("bold" in names) and ("italic" in names)
            nxt = self.text.index(f"{idx}+1c")
            if both:
                self.text.tag_add("bolditalic", idx, nxt)
            else:
                self.text.tag_remove("bolditalic", idx, nxt)
            idx = nxt

    def _toggle_style(self, tag):
        if not self.rich_var.get():
            return "break"
        try:
            a, b = self.text.index("sel.first"), self.text.index("sel.last")
        except tk.TclError:
            return "break"   # nothing selected
        if self._range_has_tag(tag, a, b):
            self.text.tag_remove(tag, a, b)
        else:
            self.text.tag_add(tag, a, b)
        if tag in ("bold", "italic"):
            self._refresh_bolditalic(a, b)
        self.text.tag_raise("bolditalic")
        self.text.tag_raise("underline")
        return "break"

    def _set_align(self, which):
        if not self.rich_var.get():
            return
        try:
            a = self.text.index("sel.first linestart")
            b = self.text.index("sel.last lineend")
        except tk.TclError:
            a = self.text.index("insert linestart")
            b = self.text.index("insert lineend")
        for t in ("left", "center", "right"):
            self.text.tag_remove(t, a, b)
        if which != "left":
            self.text.tag_add(which, a, b)

    def _extract_fmt(self, text):
        """Read the Text widget's tags into per-character arrays matching `text`."""
        n = len(text)
        if n == 0:
            return None

        def offs(index):
            c = self.text.count("1.0", index, "chars")
            return int(c[0]) if c else 0

        bold = [False] * n; italic = [False] * n; underline = [False] * n
        align = ["left"] * n
        for name, arr in (("bold", bold), ("italic", italic), ("underline", underline)):
            r = self.text.tag_ranges(name)
            for k in range(0, len(r), 2):
                for p in range(max(0, offs(r[k])), min(offs(r[k + 1]), n)):
                    arr[p] = True
        for name in ("center", "right"):
            r = self.text.tag_ranges(name)
            for k in range(0, len(r), 2):
                for p in range(max(0, offs(r[k])), min(offs(r[k + 1]), n)):
                    align[p] = name
        return {"bold": bold, "italic": italic, "underline": underline, "align": align}

